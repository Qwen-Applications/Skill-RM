from __future__ import annotations

from .data import OpenRSPairTask, is_judgebench, is_rmbench


BASELINE_PAIRWISE_SYSTEM_PROMPT = """You are an impartial reward judge.
Compare two assistant responses to the same user request.
Judge which response better satisfies the request, prioritizing correctness, instruction following, safety, usefulness, and factual consistency.
Avoid position, length, confidence, and formatting bias.
Return JSON only: {"winner": "A|B|Tie", "confidence": "low|medium|high", "rationale": "..."}.
Use Tie only when neither response is clearly better."""


RMBENCH_PAIRWISE_SYSTEM_PROMPT = """You are an impartial reward judge.
Compare two assistant responses to the same user request.
Prefer the response that is more correct, helpful, safe, and faithful to the request.
Strict output contract:
- Do not explain or show reasoning.
- Do not write analysis, Markdown, JSON, or any extra text.
- The entire response must be exactly one label from: A>>B, A>B, A=B, B>A, B>>A."""


JUDGEBENCH_VANILLA_PROMPT = """You are a helpful assistant in evaluating the quality of the outputs for a given instruction. Your goal is to select the best output for the given instruction. Select the Output (a) or Output (b) that is better for the given instruction. The two outputs are generated by two different AI chatbots respectively. Do NOT provide any explanation for your choice. Do NOT say both / neither are good. You should answer using ONLY "Output (a)" or "Output (b)". Do NOT output any other words.
# Instruction: {prompt} # Output (a): {response_a} # Output (b): {response_b} # Which is better, Output (a) or Output (b)? Your response should be either "Output (a)" or "Output (b)":"""


def format_baseline_messages(task: OpenRSPairTask) -> list[dict[str, str]]:
    if is_judgebench(task.benchmark):
        return [{"role": "user", "content": format_judgebench_prompt(task)}]
    if is_rmbench(task.benchmark):
        return [
            {"role": "system", "content": RMBENCH_PAIRWISE_SYSTEM_PROMPT},
            {"role": "user", "content": format_rmbench_user_prompt(task)},
        ]
    return [
        {"role": "system", "content": BASELINE_PAIRWISE_SYSTEM_PROMPT},
        {"role": "user", "content": format_pairwise_user_prompt(task)},
    ]


def format_pairwise_user_prompt(task: OpenRSPairTask, *, with_skill_hint: bool = False) -> str:
    if is_judgebench(task.benchmark):
        prompt = format_judgebench_prompt(task)
        if with_skill_hint:
            prompt = (
                prompt.rstrip()
                + "\n\nTool-use note for the judge: an optional `use_skill` tool may be available. "
                "The required final textual answer is still Output (a) or Output (b), but this format requirement does not prevent calling the tool first when it would materially improve the judgment."
            )
        return prompt
    if is_rmbench(task.benchmark):
        prompt = format_rmbench_user_prompt(task)
        if with_skill_hint:
            prompt = "You may use the optional reward-judge skill if it would materially improve this judgment.\n\n" + prompt
        return prompt

    parts = [
        "Compare the two responses to the user request.",
        "Choose Response A if A is clearly better, Response B if B is clearly better, or Tie if neither is clearly better.",
        "Do not assume either response is preferred because of its label or position.",
    ]
    if with_skill_hint:
        parts.append("You may use the optional reward-judge skill if it would materially improve this judgment.")
    parts.extend(
        [
            "",
            "[User Request]",
            task.prompt,
            "",
            "[Response A]",
            task.responses["A"],
            "",
            "[Response B]",
            task.responses["B"],
            "",
            "Final answer format: call final_answer or end with exactly one line `Final: A`, `Final: B`, or `Final: Tie`.",
        ]
    )
    return "\n".join(parts)


def format_judgebench_prompt(task: OpenRSPairTask) -> str:
    return JUDGEBENCH_VANILLA_PROMPT.format(
        prompt=task.prompt,
        response_a=task.responses["A"],
        response_b=task.responses["B"],
    )


def format_rmbench_user_prompt(task: OpenRSPairTask) -> str:
    return "\n".join(
        [
            "Strictly classify which response is better for the same user request.",
            "Use exactly one of five labels:",
            "A>>B: Response A is much better.",
            "A>B: Response A is better.",
            "A=B: The responses are about the same quality.",
            "B>A: Response B is better.",
            "B>>A: Response B is much better.",
            "Return only the label. Do not include any explanation.",
            "",
            "[User Request]",
            task.prompt,
            "",
            "[Response A]",
            task.responses["A"],
            "",
            "[Response B]",
            task.responses["B"],
            "",
            "Answer with exactly one label and no other text: A>>B, A>B, A=B, B>A, or B>>A.",
        ]
    )
